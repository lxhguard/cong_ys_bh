#!/usr/bin/env python3
"""扫描 markdown/ 下 .md / .html / .htm，生成：
  - docs-manifest.json  （HTTP 下可 fetch）
  - docs-data.js        （file:// 双击打开也能用，内嵌路径+正文）

本地用法：
  python3 scripts/gen-docs-manifest.py
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DOCS_ROOT = ROOT / "markdown"
OUT_JSON = ROOT / "docs-manifest.json"
OUT_JS = ROOT / "docs-data.js"
DOC_GLOBS = ("*.md", "*.html", "*.htm")


def main() -> None:
    files: list[str] = []
    contents: dict[str, str] = {}

    if DOCS_ROOT.is_dir():
        found: dict[str, Path] = {}
        for pattern in DOC_GLOBS:
            for path in DOCS_ROOT.rglob(pattern):
                if not path.is_file():
                    continue
                rel = path.relative_to(ROOT).as_posix()
                found[rel] = path
        for rel in sorted(found.keys()):
            files.append(rel)
            contents[rel] = found[rel].read_text(encoding="utf-8")

    payload = {"files": files, "contents": contents}

    OUT_JSON.write_text(
        json.dumps({"files": files}, ensure_ascii=False, indent=2) + "\n",
        encoding="utf-8",
    )

    # 转成 JS 字面量；转义 < 避免 HTML 中 </script> 截断脚本
    js_literal = json.dumps(payload, ensure_ascii=False).replace("<", "\\u003c")
    js = (
        "/* auto-generated by scripts/gen-docs-manifest.py — do not edit */\n"
        "window.__DOCS_DATA__ = "
        + js_literal
        + ";\n"
    )
    OUT_JS.write_text(js, encoding="utf-8")

    print(f"wrote {OUT_JSON.relative_to(ROOT)} ({len(files)} files)")
    print(f"wrote {OUT_JS.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
